"""Hardened grader used by the example tasks.

Usage: python check.py WORKSPACE [--isolated] [--canonical FILE ...]

Runs the hidden tests in a child process with conftest loading disabled and a
pinned config, then scores from the JUnit XML rather than the exit code:
reward = (expected test IDs that passed) / (expected test IDs), where the IDs
come from expected.json, so skipped, deselected, renamed or never-collected
tests cost reward. The child runs with `python -P`, so the workspace is not on
sys.path when pytest itself is imported (a workspace `pytest.py` cannot shadow
it); the workspace is added afterwards through pytest's `pythonpath` option.
Prints the reward as the last line of stdout.

Without --isolated this is hardened, not secure: the solution still runs
inside the test process and can patch pytest at import time.

--isolated never imports the solution into the test process. The hidden tests
import a generated proxy module instead, which forwards each call as tagged
JSON to worker.py, a separate process that imports the real solution. The
grader's pytest, its reports and its JUnit file are out of the solution's reach.
It is still not a sandbox: the worker runs with the user's permissions.

--canonical additionally requires each named workspace file to parse to the
same AST as the reference solution. That is deliberately over-fit: it exists
so the examples include a verifier that rejects valid rewrites. The stored digests
are ast.dump output, which can change between Python versions: rerun
examples/sync.py under the interpreter you grade with.
"""

import argparse
import ast
import hashlib
import json
import subprocess
import sys
import tempfile
import xml.etree.ElementTree as ET
from pathlib import Path

HERE = Path(__file__).resolve().parent


def ast_digest(path: Path) -> str:
    tree = ast.parse(path.read_text(encoding="utf-8"))
    return hashlib.sha256(ast.dump(tree, include_attributes=False).encode()).hexdigest()


PROXY = '''"""Generated by check.py --isolated: forwards calls to the solution worker."""
import builtins
import json
import subprocess
import sys

from wire import decode, encode

_proc = None


def _worker():
    global _proc
    if _proc is None:
        _proc = subprocess.Popen(
            [sys.executable, {worker!r}, {workspace!r}, {module!r}],
            cwd={workspace!r}, stdin=subprocess.PIPE, stdout=subprocess.PIPE,
            stderr=subprocess.DEVNULL, text=True, encoding="utf-8",
        )
    return _proc


def _call(name, args, kwargs):
    proc = _worker()
    try:
        proc.stdin.write(json.dumps({{"fn": name, "args": encode(list(args)), "kwargs": encode(kwargs)}}) + "\\n")
        proc.stdin.flush()
        line = proc.stdout.readline()
    except OSError as e:
        raise RuntimeError("solution worker is gone") from e
    if not line:
        raise RuntimeError("solution worker exited")
    resp = json.loads(line)
    if resp.get("ok") is True:
        return decode(resp["value"])
    exc = getattr(builtins, str(resp.get("type")), None)
    if not (isinstance(exc, type) and issubclass(exc, Exception)):
        exc = RuntimeError
    raise exc(str(resp.get("message")))


def __getattr__(name):
    if name.startswith("__"):
        raise AttributeError(name)
    return lambda *args, **kwargs: _call(name, args, kwargs)
'''


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("workspace", type=Path)
    ap.add_argument("--canonical", action="append", default=[])
    ap.add_argument("--isolated", action="store_true")
    args = ap.parse_args()
    meta = json.loads((HERE / "expected.json").read_text())

    for rel in args.canonical:
        target = args.workspace / rel
        if not target.is_file() or ast_digest(target) != meta["canonical"][rel]:
            print(f"{rel} does not match the reference solution")
            print(0.0)
            return

    with tempfile.TemporaryDirectory() as tmp:
        xml_path = Path(tmp) / "junit.xml"
        workspace = args.workspace.resolve()
        import_root, cwd = workspace, workspace
        if args.isolated:
            import_root = cwd = Path(tmp) / "proxy"
            import_root.mkdir()
            (import_root / "wire.py").write_text((HERE / "wire.py").read_text(encoding="utf-8"), encoding="utf-8")
            for module in meta["modules"]:
                (import_root / f"{module}.py").write_text(
                    PROXY.format(worker=str(HERE / "worker.py"), workspace=str(workspace), module=module),
                    encoding="utf-8",
                )
        cmd = [
            sys.executable, "-P", "-m", "pytest", "-q", "-p", "no:cacheprovider", "--noconftest",
            "-c", str(HERE / "pytest.ini"), "--rootdir", str(HERE),
            "-o", f"pythonpath={import_root.as_posix()}",
            f"--junitxml={xml_path}", str(HERE / "hidden"),
        ]
        proc = subprocess.run(cmd, cwd=cwd, capture_output=True, text=True, timeout=120)
        print(proc.stdout[-2000:])
        if not xml_path.is_file():
            print("no JUnit report: the test process died before writing results")
            print(0.0)
            return
        expected = set(meta["tests"])
        passed = set()
        for case in ET.parse(xml_path).getroot().iter("testcase"):
            case_id = f"{case.get('classname')}::{case.get('name')}"
            if case_id in expected and not any(c.tag in ("failure", "error", "skipped") for c in case):
                passed.add(case_id)
    print(len(passed) / len(expected))


if __name__ == "__main__":
    main()
