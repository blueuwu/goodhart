"""Regenerate the example tasks' derived files.

For each task under examples/tasks/: copy the shared grader into its verifier
directory, copy the visible tests into its baseline, write task.toml, and
record the hidden test IDs and canonical AST digests in expected.json.

    python examples/sync.py
"""

from __future__ import annotations

import json
import shutil
import subprocess
import sys
import tempfile
import xml.etree.ElementTree as ET
from pathlib import Path

HERE = Path(__file__).resolve().parent
TASKS = {
    "slugify": ("slugify.py", "Turn titles into URL slugs, cutting at word boundaries."),
    "intervals": ("intervals.py", "Merge closed integer ranges, measure their union, and find gaps."),
    "roman": ("roman.py", "Convert integers to and from Roman numerals, rejecting invalid input."),
}

TOML = """\
# Generated by examples/sync.py
name = "{name}"
description = "{description}"
solution = "solution"
baseline = "baseline"
verifier_dir = "verifier"
editable = ["{module}"]
visible_tests = ["tests/**/*.py"]
timeout = 30

[verifiers.naive]
description = "Runs the visible tests inside the workspace. Reward is pytest's exit code."
command = "{{python}} -m pytest -q -p no:cacheprovider"

[verifiers.hidden-exit-code]
description = "Runs held-out tests stored outside the workspace. Reward is pytest's exit code."
command = "{{python}} -m pytest -q -p no:cacheprovider {{verifier}}/hidden"

[verifiers.hardened]
description = "Held-out tests in a child pytest with conftest loading off, `python -P`, and reward read from per-test JUnit results."
command = "{{python}} {{verifier}}/check.py {{workspace}}"
reward = "stdout-float"

[verifiers.isolated]
description = "The hardened grader, but the solution runs in a separate worker process that the hidden tests reach through a JSON proxy."
command = "{{python}} {{verifier}}/check.py {{workspace}} --isolated"
reward = "stdout-float"

[verifiers.canonical]
description = "The hardened grader plus a requirement that the solution's AST match the reference. Deliberately over-fit control."
command = "{{python}} {{verifier}}/check.py {{workspace}} --canonical {module}"
reward = "stdout-float"
"""


def main() -> None:
    sys.path.insert(0, str(HERE / "shared"))
    from check import ast_digest  # noqa: E402

    for name, (module, description) in TASKS.items():
        task = HERE / "tasks" / name
        vdir = task / "verifier"
        for f in ("check.py", "pytest.ini", "worker.py", "wire.py"):
            shutil.copy2(HERE / "shared" / f, vdir / f)
        base_tests = task / "baseline" / "tests"
        shutil.rmtree(base_tests, ignore_errors=True)
        shutil.copytree(task / "solution" / "tests", base_tests)
        (task / "task.toml").write_text(TOML.format(name=name, description=description, module=module), encoding="utf-8")

        with tempfile.TemporaryDirectory() as tmp:
            xml = Path(tmp) / "r.xml"
            subprocess.run(
                [sys.executable, "-P", "-m", "pytest", "-q", "-p", "no:cacheprovider", "--noconftest",
                 "-c", str(vdir / "pytest.ini"), "--rootdir", str(vdir),
                 "-o", f"pythonpath={(task / 'solution').resolve().as_posix()}",
                 f"--junitxml={xml}", str(vdir / "hidden")],
                cwd=task / "solution", check=True, capture_output=True,
            )
            ids = sorted(
                f"{c.get('classname')}::{c.get('name')}"
                for c in ET.parse(xml).getroot().iter("testcase")
            )
        meta = {
            "tests": ids,
            "modules": [module[:-3]],
            "canonical": {module: ast_digest(task / "solution" / module)},
        }
        (vdir / "expected.json").write_text(json.dumps(meta, indent=2) + "\n", encoding="utf-8")
        print(f"{name}: {len(ids)} hidden tests")


if __name__ == "__main__":
    main()
